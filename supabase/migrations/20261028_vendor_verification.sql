-- 8. Stored Procedure (RPC): review_vendor_application
-- Provides atomic, secure state transitions with audit logging
CREATE OR REPLACE FUNCTION public.review_vendor_application(
  vendor_id BIGINT,
  new_status TEXT,
  rejection_notes TEXT DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  updated_record RECORD;
BEGIN
  -- Strict server-side authorization check
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'Access Denied: Only authorized administrators can review vendor applications.'
      USING ERRCODE = '42501';
  END IF;

  -- Validate allowed status
  IF new_status NOT IN ('approved', 'rejected') THEN
    RAISE EXCEPTION 'Invalid verification status: "%". Must be "approved" or "rejected".', new_status
      USING ERRCODE = '22023';
  END IF;

  -- Update vendor status
  UPDATE public.vendors
  SET
    verification_status = new_status,
    verified = (new_status = 'approved'),
    reviewed_by = auth.uid(),
    reviewed_at = now(),
    rejection_reason = CASE WHEN new_status = 'rejected' THEN rejection_notes ELSE NULL END,
    updated_at = now()
  WHERE id = vendor_id
  RETURNING * INTO updated_record;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Vendor application with ID % not found.', vendor_id
      USING ERRCODE = 'P0002';
  END IF;

  RETURN to_jsonb(updated_record);
END;
$$;

